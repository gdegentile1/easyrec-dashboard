    private final DataSource dataSource;

    private TestDatabase(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    /** The core tables and the pattern tables. */
    public static TestDatabase create() {
        return create(true);
    }

    /** The core tables, and the pattern tables when {@code withPatterns}. */
    public static TestDatabase create(boolean withPatterns) {
        TestDatabase database = empty();
        CORE_TABLES.forEach(database::exec);
        if (withPatterns) {
            PATTERN_TABLES.forEach(database::exec);
        }
        return database;
    }

    /** A database with no dashboard table at all. */
    public static TestDatabase empty() {
        return new TestDatabase(h2("dashboard" + NEXT.incrementAndGet()));
    }

    public DataSource dataSource() {
        return dataSource;
    }

    public JdbcDashboardDao dao() {
        return new JdbcDashboardDao(dataSource);
    }

    public TestDatabase exec(String sql) {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(sql);
        } catch (SQLException failure) {
            throw new IllegalStateException(sql, failure);
        }
        return this;
    }

    // ------------------------------------------------------------------------- inserts

    public TestDatabase template(int id, String path) {
        return exec("INSERT INTO ER_DASHBOARD_TEMPLATE (TEMPLATE_ID, FULL_PATH) VALUES (" + id + ", " + text(path) + ")");
    }

    /** A batch run by {@code user}, at {@code sysTime} ({@code yyyy-MM-dd HH:mm:ss}, or null). */
    public TestDatabase batch(int id, String sysTime, Integer status, String user) {
        return exec("INSERT INTO ER_DASHBOARD_BATCH (BATCH_ID, USER_NAME, STATUS, SYS_TIME, PURGE_STATUS) VALUES ("
                + id + ", " + text(user) + ", " + status + ", "
                + (sysTime == null ? "NULL" : "TIMESTAMP '" + sysTime + "'") + ", 0)");
    }

    public TestDatabase batch(int id, String sysTime) {
        return batch(id, sysTime, 1, "ops");
    }

    public TestDatabase run(int runId, int batchId, int templateId) {
        return exec("INSERT INTO ER_DASHBOARD_RUN (RUN_ID, BATCH_ID, REC_TYPE, TEMPLATE_ID, STATUS, PURGE_STATUS) "
                + "VALUES (" + runId + ", " + batchId + ", 0, " + templateId + ", 1, 0)");
    }

    public TestDatabase context(int runId, int position, int templateId) {
        return exec("INSERT INTO ER_DASHBOARD_RUN_CONTEXT (RUN_ID, POSITION, TEMPLATE_ID, STATUS) VALUES ("
                + runId + ", " + position + ", " + templateId + ", 0)");
    }

    /** A row statistic whose breaks are all unmatched rows: {@code max(source, target) - matched}. */
    public TestDatabase rowStats(int runId, int templateId, int status, long source, long target, long matched) {
        return rowStats(runId, templateId, status, source, target, 0, 0, Math.max(source, target) - matched, matched);
    }

    public TestDatabase rowStats(int runId, int templateId, int status, long source, long target,
                                 long missingSource, long missingTarget, long unmatched, long matched) {
        return exec("INSERT INTO ER_DASHBOARD_STAT_ROWS (RUN_ID, TEMPLATE_ID, STATUS, ROWS_SOURCE, ROWS_TARGET, "
                + "MISSING_SOURCE, MISSING_TARGET, UNMATCHED, MATCHED, FORCE_MATCHED, NB_COMMENTS) VALUES ("
                + runId + ", " + templateId + ", " + status + ", " + source + ", " + target + ", "
                + missingSource + ", " + missingTarget + ", " + unmatched + ", " + matched + ", 0, 0)");
    }

    public TestDatabase columnStats(int runId, int templateId, String label, String type, Double matchRatio,
                                    long unmatched, long exact) {
        return exec("INSERT INTO ER_DASHBOARD_STAT_COLS (RUN_ID, TEMPLATE_ID, COL_LABEL, COL_CLASS, COL_MATCH_PCT, "
                + "COL_NB_UNMATCH, COL_NB_EXACT_MATCH, COL_NB_TOLERANCE_MATCH, COL_NB_FORCE_MATCH) VALUES ("
                + runId + ", " + templateId + ", " + text(label) + ", " + text(type) + ", " + matchRatio + ", "
                + unmatched + ", " + exact + ", 0, 0)");
    }

    public TestDatabase pattern(int id, int templateId, String signature, String description,
                                int firstSeenRun, Integer linkedPatternId) {
        return exec("INSERT INTO ER_DASHBOARD_PATTERN (PATTERN_ID, TEMPLATE_ID, SIGNATURE, DESCRIPTION, "
                + "FIRST_SEEN_RUN, LINKED_PATTERN_ID) VALUES (" + id + ", " + templateId + ", " + text(signature)
                + ", " + text(description) + ", " + firstSeenRun + ", " + linkedPatternId + ")");
    }

    /** ABOVE_THRESHOLD is reserved and always 1 today. */
    public TestDatabase patternStat(int runId, int patternId, long occurrences) {
        return exec("INSERT INTO ER_DASHBOARD_PATTERN_STAT (RUN_ID, PATTERN_ID, OCCURRENCES, ABOVE_THRESHOLD) "
                + "VALUES (" + runId + ", " + patternId + ", " + occurrences + ", 1)");
    }

    private static String text(String value) {
        return value == null ? "NULL" : "'" + value.replace("'", "''") + "'";
    }

    private static DataSource h2(String name) {
        String url = "jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1";
        return new DataSource() {
            @Override public Connection getConnection() throws SQLException { return DriverManager.getConnection(url); }
            @Override public Connection getConnection(String u, String p) throws SQLException { return getConnection(); }
            @Override public PrintWriter getLogWriter() { return null; }
            @Override public void setLogWriter(PrintWriter out) { }
            @Override public void setLoginTimeout(int seconds) { }
            @Override public int getLoginTimeout() { return 0; }
            @Override public Logger getParentLogger() { return Logger.getGlobal(); }
            @Override public <T> T unwrap(Class<T> iface) { return null; }
            @Override public boolean isWrapperFor(Class<?> iface) { return false; }
        };
    }
